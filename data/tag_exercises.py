"""Merge data/exercise_tags.json into data/library.json and rebuild data/program_index.json.

    python3 data/tag_exercises.py

Run it after editing exercise_tags.json, adding exercises, or adding/changing a program.
- Library entries get primary_muscle, muscles, pattern, role, equipment, level, unilateral,
  plane and hip_focus from the tag file (the tag file wins).
- Section-header rows that leaked into the catalog ("Daily Overview…", "Superset", …) are
  removed from the catalog; program rows that name them stay and are hidden by the app.
- Tags for hip-tab entries (hiprx-*, defined in src/lib/hip_protocol.js) go into
  library.json's `extra_tags`, which src/lib/static_data.js merges at load time.
- program_index.json summarises every program for plan design (see docs/PROGRAM_DESIGN.md).
"""
import json, re
from collections import Counter, defaultdict
from pathlib import Path

D = Path(__file__).parent
LIB = D / 'library.json'
TAGS = D / 'exercise_tags.json'
INDEX = D / 'program_index.json'
FIELDS = ['primary_muscle', 'muscles', 'pattern', 'role', 'equipment', 'level', 'unilateral', 'plane', 'hip_focus']
HEADER = re.compile(r'^(daily overview|start of workout.*overview|superset|circuit|combo cardio)\b', re.I)


def main():
    lib = json.loads(LIB.read_text())
    tf = json.loads(TAGS.read_text())
    tags, headers = tf['tags'], set(tf.get('headers', []))

    before = len(lib['exercises'])
    lib['exercises'] = [e for e in lib['exercises'] if e['id'] not in headers]
    lib_ids = {e['id'] for e in lib['exercises']}
    untagged = []
    for e in lib['exercises']:
        t = tags.get(e['id'])
        if not t:
            untagged.append(e['name'])
            continue
        for k in FIELDS:
            e[k] = t[k]
    lib['extra_tags'] = {i: {k: t[k] for k in FIELDS} for i, t in tags.items() if i not in lib_ids}
    LIB.write_text(json.dumps(lib, indent=2, ensure_ascii=False) + '\n')

    by_name = {}
    for e in lib['exercises']:
        for n in [e['name']] + (e.get('aliases') or []):
            by_name.setdefault(n.lower(), e)
    for i, t in tags.items():
        by_name.setdefault(t['name'].lower(), {'id': i, **t})

    index = []
    for key, progs in lib['programs'].items():
        for p in progs:
            weeks = p.get('weeks') or [{'week_num': 1, 'days': p.get('days', [])}]
            w1 = weeks[0]['days']
            sets_by_muscle, sets_by_pattern, roles, equipment = Counter(), Counter(), Counter(), set()
            n_ex = []
            for d in w1:
                rows = [x for x in d.get('exercises', []) if not x.get('is_alternate') and not HEADER.match(x['name'])]
                n_ex.append(len(rows))
                for x in rows:
                    e = by_name.get(x['name'].lower())
                    sets = int(x.get('sets') or len(x.get('set_targets') or []) or 3) if str(x.get('sets') or '').isdigit() or x.get('set_targets') or not x.get('sets') else 3
                    if not e or 'pattern' not in e:
                        continue
                    sets_by_muscle[e['primary_muscle']] += sets
                    sets_by_pattern[e['pattern']] += sets
                    roles[e['role']] += 1
                    equipment.update(q for q in e['equipment'] if q != 'bodyweight')
            index.append({
                'id': p.get('id'), 'name': p.get('program_name') or p.get('name'), 'group': p.get('group') or key,
                'kind': 'progression' if p.get('weeks') else 'rotation', 'weeks': len(p['weeks']) if p.get('weeks') else None,
                'days_per_week': len(w1), 'exercises_per_day': round(sum(n_ex) / max(1, len(n_ex)), 1),
                'day_focus': [d.get('focus') or d.get('day_name') for d in w1],
                'week1_sets_by_muscle': dict(sets_by_muscle.most_common()),
                'week1_sets_by_pattern': dict(sets_by_pattern.most_common()),
                'roles': dict(roles.most_common()), 'equipment': sorted(equipment),
                'description': p.get('description'),
            })
    INDEX.write_text(json.dumps({'_doc': 'Generated by data/tag_exercises.py: one summary per program, used when designing plans.',
                                 'programs': index}, indent=1, ensure_ascii=False) + '\n')
    print(f'library: {before} -> {len(lib["exercises"])} exercises ({before - len(lib["exercises"])} headers pruned), '
          f'{len(lib["extra_tags"])} extra (hip-tab) tags, {len(untagged)} untagged{": " + ", ".join(untagged[:10]) if untagged else ""}')
    print(f'program_index: {len(index)} programs')


if __name__ == '__main__':
    main()
